import assert from 'node:assert/strict';
import vm from 'node:vm';
import { documents, catalog, toText, code, backupContext, target } from './verify-research.mjs';
import { definitionMatches, definitionUnits } from '../features/definitions-model.mjs';
import { rowsReport, upsertReport, reportEntries, reportState, reportHtml, reportMarkdown, safeUrl, eventReport } from '../features/report-model.mjs';
import { buildCatalog } from '../features/research-model.mjs';
const past = eventReport({ eventKey: 'provider:test', kind: 'company', title: '画像の対照表', sourceFingerprint: 'a', url: 'https://example.com/notice', announcementText: '告知本文', evidence: [{ label: '対照表画像', url: 'https://example.com/comparison.png', localUrl: '/docs/comparison.png' }] }, { checkedAt: '2026-11-23' });
assert.equal(past.kind, 'history'); assert(past.blocks.some(block => block.source?.localUrl === '/docs/comparison.png'));
assert(past.blocks.every(block => !block.source || block.source.fetchedAt === '2026-11-23'));
const matches = definitionMatches(catalog, '本サービス');
assert(matches.some(value => value.row.docId === 'mercoin_tos' && value.quote.includes('口座の開設')));
const mits = matches.find(value => value.row.docId === 'sbivc-mits-terms');
assert(mits.quote.includes('総合NFT運営支援サービス'), 'Nested parentheses must not truncate the definition');
assert(!matches.some(value => value.row.item.index === '12. 日本国'), 'A usage restriction is not a definition');
assert(definitionMatches(catalog, '本サービス', { definitionsOnly: false }).length > matches.length);
assert(definitionMatches(catalog, '本サービス', { provider: 'メルコイン' }).every(value => value.row.provider === 'メルコイン'));
assert.deepEqual(definitionUnits('定義（文。補足。）をいう。次。'), ['定義（文。補足。）をいう。','次。']);
assert.equal(definitionMatches(catalog, '').length, 0);
assert.doesNotThrow(() => definitionMatches(catalog, '[.*+?'));
const row = matches.find(value => value.row.docId === 'mercoin_tos').row;
const entry = rowsReport('definitions', '本サービスの比較', [row, mits.row], toText);
const fixture = structuredClone(documents);
upsertReport(fixture, entry, '2026-11-23T01:00:00Z');
let saved = fixture.researchReport[0];
assert.equal(reportState(saved, catalog), 'saved');
upsertReport(fixture, { ...saved, note: '確認した対象範囲' }, '2026-11-23T02:00:00Z');
upsertReport(fixture, entry, '2026-11-23T03:00:00Z');
saved = fixture.researchReport[0];
assert.equal(saved.note, '確認した対象範囲', 'Re-adding must retain the note');
assert.equal(reportEntries(fixture.researchReport).length, 1);
const changed = structuredClone(documents); changed[row.docId].tweets.find(value => value.id === row.item.id).content += '本文更新';
assert.equal(reportState(saved, buildCatalog(changed, toText)), 'changed');
delete changed[row.docId]; assert.equal(reportState(saved, buildCatalog(changed, toText)), 'missing');
const html = reportHtml([saved], { title: '<script>alert(1)</script>', author: '担当者' }, 'https://example.com', '2026-11-23');
assert(html.includes('&lt;script&gt;')); assert(!html.includes('<script>'));
assert(html.includes('href="https://pages.mercoin.com/exchange/consent-forms/tos/"'));
assert(html.includes('https://example.com/docs/sbivc/'));
assert(html.includes('資料取得日 2026-10-06')); assert(html.includes('確認した対象範囲'));
assert.equal(safeUrl('javascript:alert(1)', 'https://example.com'), '');
const markdown = reportMarkdown([saved], { title: '比較レポート' }, 'https://example.com', '2026-11-23');
assert(markdown.includes('口座の開設')); assert(markdown.includes('資料取得日')); assert(markdown.includes('収録条文 https://example.com/document/'));
upsertReport(fixture, { id: 'report-settings', kind: 'settings', title: '保存した表題' });
const exported = backupContext.dh(fixture, {});
assert.equal(exported.version, 4); assert.equal(exported.researchReport.length, 2);
backupContext.ph(exported); assert.equal(target.researchReport[0].note, saved.note);
upsertReport(target, { ...saved, deleted: true }, '2026-11-24T00:00:00Z'); backupContext.ph(exported);
assert.equal(target.researchReport.find(value => value.id === saved.id).deleted, true);
assert.equal(reportEntries(target.researchReport).length, 0);
for (const version of [1,2,3]) assert(backupContext.fh({ ...exported, version, researchReport: undefined }, target).ok);
assert(!backupContext.fh({ ...exported, version: 5 }, target).ok);
const mergeCode = code.slice(code.indexOf('var pm='), code.indexOf('var Em=', code.indexOf('var pm=')));
const merge = vm.createContext({ X: 'legal-documents-data', Gc: 'legal-documents-base', Kc: 'legal-documents-version' }); vm.runInContext(mergeCode, merge);
const store = new Map([['legal-documents-data', JSON.stringify(fixture)], ['legal-documents-base', JSON.stringify(documents)]]);
merge.Sm(changed, { getItem: key => store.get(key) ?? null, setItem: (key, value) => store.set(key, value) });
assert.equal(JSON.parse(store.get('legal-documents-data')).researchReport[0].note, saved.note);
for (const route of ['/definitions','/research-report']) assert(code.includes(`path:\`${route}\``));
console.log('PASS: actual definitions, mention exclusion and nested context; report snapshots/change detection; safe HTML and Markdown with citations; backup v1–v4, deletion and application upgrades.');
