import assert from 'node:assert/strict';
import vm from 'node:vm';
import { readFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { documents, catalog, toText, code, backupContext, target } from './verify-research.mjs';
import { providerEvents, regulatoryEvents, findImpact, saveImpactReview, impactReviewState, selectEvents } from '../features/history-model.mjs';
import { classifyServices, matchesService, withServiceQuery } from '../features/services.mjs';
import { createMapping, upsertMapping, buildCatalog } from '../features/research-model.mjs';
const data = JSON.parse(readFileSync(new URL('../features/provider-history-data.json', import.meta.url)));
const events = providerEvents(data, documents, toText);
assert.equal(events.length, 66);
assert.equal(events.filter(event => event.provider === 'SBI VCトレード').length, 50);
assert.equal(events.flatMap(event => event.segments).length, 375);
for (const event of events) {
  const digest = url => createHash('sha256').update(readFileSync(new URL('..' + url.split('#')[0], import.meta.url))).digest('hex');
  assert.equal(digest(event.source), event.sourceSha256);
  for (const source of event.evidence) if (source.available) assert.equal(digest(source.localUrl), source.sha256);
  for (const segment of event.segments) {
    assert(segment.beforeKnown || segment.afterKnown);
    assert(!/<script|onerror=|javascript:/i.test(segment.before + segment.after));
  }
  if (event.lineage === 'legacy-vctrade') assert.equal(event.docIds.length, 0);
}
const event = id => events.find(event => event.id === id);
assert.equal(event('mercoin-35126').effectiveDate, '2024-02-14');
assert.equal(event('mercoin-35126').publishedDate, '2024-01-23');
assert.equal(event('mercoin-35126').sourceModifiedDate, '2026-04-09');
assert.equal(event('sbi-wfa43zz67u').effectiveDate, null);
assert.equal(event('sbi-4ndks8ejxdzu').effectiveDate, null);
assert.deepEqual(event('mercoin-41722').scheduledEffectiveDates, ['2024-11-26','2024-12-06']);
const maintenance = event('sbi-j3rl-is_pu').segments[0];
assert(maintenance.before.includes('12：00～13：00'));
assert(maintenance.after.includes('13：00～14：00'));
const age = event('mercoin-35126').segments[0];
assert(age.before.includes('20歳未満')); assert(age.after.includes('18歳未満'));
assert(event('sbi-p8gnt3204ee').segments.some(segment => segment.docIds.includes('sbivc-lending-manual')));
assert.deepEqual(classifyServices('sbivc-lending-terms', documents['sbivc-lending-terms']).ids, ['lending']);
assert.deepEqual(classifyServices('mercoin_auto_invest_tos', documents.mercoin_auto_invest_tos).ids, ['recurring']);
assert(!matchesService({ services: { ids: ['lending'] } }, 'spot', false));
assert(matchesService({ services: { ids: ['common'] } }, 'spot'));
assert(!matchesService({ services: { ids: ['common'] } }, 'spot', false));
assert(!matchesService({ services: { ids: ['unknown'] } }, 'spot'));
assert.equal(withServiceQuery('/provider-history?doc=x', { service: 'lending', common: '0' }), '/provider-history?doc=x&service=lending&common=0');
assert(selectEvents(events, { provider: 'メルコイン', service: 'recurring', includeCommon: false }).every(event => event.provider === 'メルコイン' && event.services.ids.includes('recurring')));
const rules = regulatoryEvents(documents, catalog, toText);
assert(rules.length > 100);
assert(rules.every(event => event.changedKeys.length && !event.eventKey.includes('undefined')));
const candidate = rules.find(event => event.changedKeys.some(key => catalog.byKey.get(key)));
const rule = candidate.changedKeys.map(key => catalog.byKey.get(key)).find(Boolean);
const company = catalog.byKey.get('sbivc-service-terms/sbivc-service-terms-a7');
const fixture = structuredClone(documents);
fixture.researchMappings = [];
upsertMapping(fixture, createMapping('custody', rule, company, 'テスト根拠'));
fixture[rule.docId].checklist = { [rule.item.id]: { status: 'reviewing', owner: 'テスト担当', regulations: [{ id: 'test-reg', article: '第1条' }] } };
