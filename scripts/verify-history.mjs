assert.equal(impact.internalRegulations.length, 1); assert.equal(impact.checklist.length, 1);
impact = findImpact(event('sbi-8v_jcz-9a'), fixture, fixtureCatalog);
assert.equal(impact.mappings[0].basis, 'document-candidate');
